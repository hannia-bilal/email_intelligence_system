import type { ActionItem, AiLogEntry, AppNotification, Email, ThreadMessage } from "../lib/types";
import { parseDeadline } from "../lib/mockAi";

const ME = "you@mailmind.ai";

const ago = (days: number, hour = 10, min = 0) => {
  const d = new Date();
  d.setDate(d.getDate() - days);
  d.setHours(hour, min, 0, 0);
  return d.toISOString();
};

const act = (id: string, text: string, label?: string, done = false): ActionItem => ({
  id,
  text,
  deadlineLabel: label,
  deadline: label ? parseDeadline(label) : undefined,
  status: done ? "Completed" : "Pending",
});

const msg = (id: string, from: string, fromEmail: string, daysAgo: number, body: string, isMe = false): ThreadMessage => ({
  id,
  from,
  fromEmail,
  to: isMe ? "customer" : ME,
  date: ago(daysAgo, 9),
  body,
  isMe,
});

